import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const dir=new URL('../dist/assets/',import.meta.url);
const context={window:{},Intl,Date,Number,JSON,Math};context.window.window=context.window;vm.createContext(context);
for(const name of ['data-model.js','ops-model.js'])vm.runInContext(readFileSync(new URL(name,dir),'utf8'),context,{filename:name});
const M=context.window.CRModel,O=context.window.CROps;
const active={status:'INPROGRESS',action:'Need review',dueDate:'2026-10-30',title:'A'};
const closed={...active,status:'CLOSED'};
assert.equal(O.dueKey(46310),'2026-10-15');
assert.equal(O.dueKey('46310'),'2026-10-15');
assert.equal(O.dueKey('2026-10-31'),'2026-10-31');
assert.equal(O.dueKey('31/10/2026'),'2026-10-31');
assert.equal(O.dueKey('31/02/2026'),null,'Invalid dates must not become due dates');
assert.equal(O.followupBucket(active,'2026-10-31'),'overdue');
assert.equal(O.followupBucket({...active,dueDate:'2026-10-31'},'2026-10-31'),'today');
assert.equal(O.followupBucket({...active,dueDate:'2026-11-01'},'2026-10-31'),'upcoming');
assert.equal(O.followupBucket({...active,dueDate:''},'2026-10-31'),'unscheduled');
assert.equal(O.followupBucket(closed,'2026-10-31'),'complete');
assert.equal(O.needsAction(closed),false);
assert.equal(O.needsAction(active),true);
const order=[{...active,dueDate:''},{...active,dueDate:'2026-11-01'},{...active,dueDate:'2026-10-30'}].sort(O.compareFollowups);
assert.equal(order[0].dueDate,'2026-10-30');
assert.equal(order[2].dueDate,'');
assert.equal(O.reconBucket({status:'CLOSED'}),'missing');
assert.equal(O.reconBucket({status:'INPROGRESS',reconMonth:'September'}),'recorded');
assert.equal(O.reconBucket({status:'CLOSED',manualRekon:'Sudah Rekon'}),'local');
assert.equal(O.isVerified({reconMonth:'September'}),false,'Period alone is not evidence');
assert.equal(O.isVerified({verification:{evidenceReference:'DOC01',verifiedBy:'QA',verifiedAt:'2026-10-30'}}),true);
console.log('PASS v3.1 operations — due date, follow-up ordering and reconciliation semantics');
