import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root=new URL('../dist/', import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');
const context={window:{},console,Date,Number,Set,Intl,JSON,Math};context.window.window=context.window;vm.createContext(context);
vm.runInContext(read('data.js'),context,{filename:'data.js'});
vm.runInContext(read('assets/data-model.js'),context,{filename:'data-model.js'});
const d=context.window.CR_WORKBOOK_SNAPSHOT,m=context.window.CRModel;
assert.equal(d.records.length,0,'Safe GitHub source must contain no corporate CR records');
const records=d.records;
assert.equal(records.length,new Set(records.map(x=>x.key)).size,'unique keys');
assert.equal(records.filter(x=>x.sheet==='CR Ultimate'&&x.number==null).length,0,'Exclude unnumbered subrows');
assert.equal(m.yearOf(46310),2026);
assert.equal(m.yearOf('Tel.85/UM 000/TSEL-IT/2024'),2024);
assert.equal(m.statusGroup('INPROGRESS'),'active');
assert.equal(m.statusGroup('CLOSED'),'closed');
assert.equal(m.statusGroup('NOT STARTED'),'active');
assert.equal(m.statusGroup('DONE'),'done');
assert.equal(m.statusGroup('CANCELED'),'cancel');
assert.equal(m.progressPct(.1),10);
assert.equal(m.progressPct(1),100);
assert.equal(m.progressPct('70'),70);
assert.equal(m.progressPct(''),null);
assert.equal(m.safeTextForExcel('=HYPERLINK("example","bad")').startsWith("'"),true);
const reconWithMonth={reconMonth:'Juni',yearRekon:2026,reconRaw:null};
assert.equal(m.hasRekon(reconWithMonth),true);
assert.ok(!m.reconLabel(reconWithMonth).includes('Terkonfirmasi'),'Month not final confirmation');
const toMatch={title:'AA',crId:'CR01',rowHint:1};
assert.equal(m.stableMatch(toMatch,[{title:'AA',crId:'CR01',rowHint:50}]).rowHint,50,'Row can move');
assert.throws(()=>m.stableMatch(toMatch,[{title:'AA',crId:'CR01',rowHint:1},{title:'AA',crId:'CR01',rowHint:2}]),/beberapa baris/);
assert.throws(()=>m.stableMatch(toMatch,[]),/berubah/);
const matrix=m.parseCSV('"key","action"\r\n"a","note, and ""quotes"""\r\n');
assert.equal(matrix[1][1],'note, and "quotes"');
const synthetic=m.parseRows('CR Ultimate',[[],[],[1,'TEST-001','Synthetic project','INPROGRESS',.5,null,'Note','Test action']]);
assert.equal(synthetic.length,1);
assert.equal(synthetic[0].crId,'TEST-001');
assert.equal(m.getEditableFields('CR Ultimate').status,3);
assert.equal(m.getEditableFields('Cost CR').month,22);
assert.equal(m.getEditableFields('UPCOMING CR').status,undefined);
console.log('PASS sanitized model — synthetic records, no business data, semantics, guardrails, CSV and mappings');
